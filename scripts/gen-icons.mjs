// Regenerates src/components/icons.ts from every icon name used in the registry and batch files.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const lucide = require('lucide-react')
const files = ['src/tools/registry.ts', ...readdirSync('src/tools/batches').map((f) => `src/tools/batches/${f}`)]
const names = new Set(['Wrench', 'ImageIcon'])
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(/icon:\s*'([A-Za-z0-9]+)'/g)) names.add(m[1])
const ok = [...names].filter((n) => lucide[n]).sort()
const missing = [...names].filter((n) => !lucide[n])
if (missing.length) console.warn('[gen-icons] unknown lucide icons (fallback used):', missing.join(', '))
const list = ok.join(', ')
writeFileSync('src/components/icons.ts', `// Auto-generated by scripts/gen-icons.mjs: icons used by the tool registry\nimport { ${list}, Wrench as Fallback } from 'lucide-react'\nimport type { LucideIcon } from 'lucide-react'\nexport const ICONS: Record<string, LucideIcon> = { ${list} }\nexport const getIcon = (n: string): LucideIcon => ICONS[n] ?? Fallback\n`)
console.log(`[gen-icons] ${ok.length} icons`)
