import assert from 'node:assert/strict'
import * as ip from '../../../src/lib/b5/ip.ts'
const c = ip.parseCidr('192.168.10.77/26')
const s = ip.subnetInfo(c.addr, c.prefix)
assert.equal(ip.fmtV4(s.network), '192.168.10.64'); assert.equal(ip.fmtV4(s.last), '192.168.10.127'); assert.equal(s.usable, 62n)
assert.equal(ip.fmtV4(s.mask), '255.255.255.192')
assert.equal(ip.parseCidr('10.0.0.1/255.255.0.0').prefix, 16)
assert.equal(ip.fmtV6(ip.parseV6('2001:0db8:0000:0000:0000:ff00:0042:8329')), '2001:db8::ff00:42:8329')
assert.equal(ip.fmtV6(ip.parseV6('::1')), '::1'); assert.equal(ip.fmtV6(0n), '::')
assert.equal(ip.fmtV6(ip.parseV6('::ffff:192.0.2.1')), '::ffff:c000:201')
assert.deepEqual(ip.rangeToCidrs(4, ip.parseV4('10.0.0.0'), ip.parseV4('10.0.0.255')), ['10.0.0.0/24'])
assert.deepEqual(ip.rangeToCidrs(4, ip.parseV4('10.0.0.1'), ip.parseV4('10.0.0.6')), ['10.0.0.1/32', '10.0.0.2/31', '10.0.0.4/31', '10.0.0.6/32'])
assert.equal(ip.addrType(ip.parseAddr('172.20.1.1')), 'Private (RFC 1918)')
assert.equal(ip.addrType(ip.parseAddr('fe80::1')), 'Link-local')
assert.equal(ip.reverseDns(ip.parseAddr('1.2.3.4')), '4.3.2.1.in-addr.arpa')
assert.equal(ip.splitSubnets(c.addr, 24, 26).out.length, 4)
assert.equal(ip.parseV4('256.1.1.1'), null); assert.equal(ip.parseV6('1::2::3'), null)
assert.match(ip.randomUla(), /^fd[0-9a-f]{2}:/)
console.log('ip ok')
