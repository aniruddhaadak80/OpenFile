import assert from 'node:assert/strict'
import * as P from '../../../src/lib/b5/pgp.ts'
const alice = await P.generate({ name: 'Alice', email: 'alice@example.com', passphrase: 'pw', type: 'ecc' })
const bob = await P.generate({ name: 'Bob', email: 'bob@example.com', type: 'curve25519' })
const info = await P.keyInfo(alice.privateKey)
assert.equal(info[0].isPrivate, true); assert.equal(info[0].locked, true); assert.match(info[0].users[0], /Alice/)
const enc = await P.encrypt({ data: 'secret ✓', publicKeys: bob.publicKey, signKey: alice.privateKey, signPass: 'pw', armor: true })
assert.match(enc, /BEGIN PGP MESSAGE/)
const dec = await P.decrypt({ message: enc, privateKey: bob.privateKey, verifyKeys: alice.publicKey })
assert.equal(dec.data, 'secret ✓'); assert.equal(dec.signatures[0].ok, true)
await assert.rejects(P.decrypt({ message: enc, privateKey: alice.privateKey, passphrase: 'pw' }))
await assert.rejects(P.decrypt({ message: enc, privateKey: alice.privateKey, passphrase: 'bad' }), /Wrong passphrase/)
const pwEnc = await P.encrypt({ data: new Uint8Array([1, 2, 3]), publicKeys: '', password: 'x', armor: false, filename: 'a.bin' })
const pwDec = await P.decrypt({ message: pwEnc, password: 'x', binary: true }); assert.deepEqual(Array.from(pwDec.data), [1, 2, 3])
const signed = await P.sign({ text: 'hello', privateKey: alice.privateKey, passphrase: 'pw', detached: false })
const v = await P.verify({ signed, publicKeys: alice.publicKey }); assert.equal(v.signatures[0].ok, true); assert.equal(v.text, 'hello')
const v2 = await P.verify({ signed: signed.replace('hello', 'hellO'), publicKeys: alice.publicKey }); assert.equal(v2.signatures[0].ok, false)
const det = await P.sign({ text: 'doc', privateKey: alice.privateKey, passphrase: 'pw', detached: true })
assert.equal((await P.verify({ signed: 'doc', detachedSig: det, publicKeys: alice.publicKey })).signatures[0].ok, true)
console.log('pgp ok')
