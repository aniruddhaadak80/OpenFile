import assert from 'node:assert/strict'
import * as T from '../../../src/lib/b5/textops.ts'
assert.equal(T.reverseText('abc 👍🏽', 'chars'), '👍🏽 cba')
assert.equal(T.reverseText('one two three', 'words'), 'three two one')
assert.equal(T.reverseText('a\nb', 'lines'), 'b\na')
assert.equal(T.reverseText('hello world', 'each-word'), 'olleh dlrow')
const n = T.addLineNumbers('a\nb\n\nc', { start: 1, step: 1, format: '. ', pad: 'none', skipEmpty: true }); assert.equal(n, '1. a\n2. b\n\n3. c')
assert.equal(T.removeLineNumbers(n), 'a\nb\n\nc')
assert.equal(T.removeLineNumbers('  10\tfoo\n[2] bar\n3) baz'), 'foo\nbar\nbaz')
assert.equal(T.slugify('Hello, Wörld! Ça va? Привет & добро'), 'hello-woerld-ca-va-privet-and-dobro')
assert.equal(T.slugify('The Quick Brown Fox', { sep: '_', lower: true, max: 0, translit: true, stop: true }), 'quick_brown_fox')
assert.equal(T.slugify('a very long title that keeps going', { sep: '-', lower: true, max: 20, translit: true, stop: false }), 'a-very-long-title')
assert.deepEqual(T.extract('Mail a@b.com or A@B.com, see https://x.dev/p?q=1. ip 10.0.0.1 and 999.1.1.1', 'email'), ['a@b.com'])
assert.deepEqual(T.extract('see https://x.dev/p?q=1. ok', 'url'), ['https://x.dev/p?q=1'])
assert.deepEqual(T.extract('ip 10.0.0.1 and 999.1.1.1', 'ipv4'), ['10.0.0.1'])
assert.deepEqual(T.extract('card 4111 1111 1111 1111 and 1234 5678 9012 3456', 'card'), ['4111 1111 1111 1111'])
assert.deepEqual(T.setOp(['a', 'b', 'c'], ['B', 'd'], 'intersection', true), ['b'])
assert.deepEqual(T.setOp(['a', 'b'], ['b', 'c'], 'xor', false), ['a', 'c'])
assert.equal(T.FANCY.find((f) => f.id === 'bold').fn('Ab1'), '𝐀𝐛𝟏')
assert.equal(T.FANCY.find((f) => f.id === 'italic').fn('h'), 'ℎ')
assert.equal(T.FANCY.find((f) => f.id === 'double').fn('R'), 'ℝ')
