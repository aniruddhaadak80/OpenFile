import { useEffect, useState } from 'react'
import { FileKey2, KeyRound, Download, ShieldCheck } from 'lucide-react'
import { Button, Dropzone, ResultCard, Switch, ToolGrid, Progress, ErrorNote, Input, Field, Spinner, FileChip, Card, useJob } from '@/components/ui'
import { pdfBlob } from '@/lib/pdf'
import { baseName, downloadBlob } from '@/lib/files'
import { toast } from '@/components/toast'
import { FileBar, PDF_ACCEPT, PageStepper, usePdfDoc } from './_core/kit'
import { readBytes, Note, RectEditor, usePage, vpToPdf } from './_b1/ui'
import type { Identity } from './_b1/sig'

export default function SignPdfCertificate() {
  const [file, setFile] = useState<File | null>(null)
  const { doc, numPages, error } = usePdfDoc(file)
  const [cert, setCert] = useState<File | null>(null)
  const [password, setPassword] = useState('')
  const [id, setId] = useState<Identity | null>(null)
  const [reason, setReason] = useState(''), [location, setLocation] = useState(''), [contact, setContact] = useState('')
  const [visible, setVisible] = useState(true)
  const [page, setPage] = useState(0)
  const img = usePage(doc, page + 1, 640)
  const [box, setBox] = useState<{ x0: number; y0: number; x1: number; y1: number } | null>(null)
  const [result, setResult] = useState<Blob | null>(null)
  const [maker, setMaker] = useState(false)
  const [mk, setMk] = useState({ name: '', email: '', org: '', password: '' })
  const job = useJob(), unlock = useJob(), make = useJob()
  const reset = () => { setFile(null); setResult(null); setBox(null); setPage(0) }

  useEffect(() => { if (img && !box) setBox({ x0: img.w - 250, y0: img.h - 100, x1: img.w - 40, y1: img.h - 40 }) }, [img]) // eslint-disable-line
  useEffect(() => { setId(null) }, [cert])

  const open = () => unlock.run(async () => {
    if (!cert) return
    const m = await import('./_b1/sig')
    const ident = m.readP12(await readBytes(cert), password)
    if (ident.notAfter < new Date()) toast('This certificate has expired. Signatures will show as not valid.', 'error')
    setId(ident)
  })
  const makeCert = () => make.run(async () => {
    if (!mk.name.trim() || mk.password.length < 4) throw new Error('Enter your name and a password of at least 4 characters.')
    const m = await import('./_b1/sig')
    const p12 = await m.makeTestCertificate({ name: mk.name.trim(), email: mk.email.trim() || undefined, org: mk.org.trim() || undefined, password: mk.password })
    const f = new File([p12 as BlobPart], `${mk.name.trim().replace(/\s+/g, '-')}.p12`, { type: 'application/x-pkcs12' })
    downloadBlob(f, f.name)
    setCert(f); setPassword(mk.password); setMaker(false)
    setTimeout(() => setId(m.readP12(p12, mk.password)), 0)
    toast('Certificate created and saved. Keep the file and password safe.', 'success')
  })
  const sign = () => job.run(async (setP) => {
    if (!file || !id || !doc) return
    const m = await import('./_b1/sig'); setP(0.3)
    let vis = null
    if (visible && box) { const vp = (await doc.getPage(page + 1)).getViewport({ scale: 1 }); vis = { page, rect: vpToPdf(vp, box) } }
    const out = await m.signPdf(await readBytes(file), id, { reason: reason || undefined, location: location || undefined, contact: contact || undefined, visible: vis })
    setResult(pdfBlob(out)); setP(1); toast('PDF signed', 'success')
  })

  if (!file) return <Dropzone accept={PDF_ACCEPT} onFiles={(f) => setFile(f[0])} label="Drop the PDF you want to sign with a certificate" sub="You will need a .p12 or .pfx certificate file. Or create one here." />
  return (
    <div className="space-y-4">
      <FileBar file={file} pages={numPages} onReset={reset} />
      {error && <ErrorNote error={error} />}
      {result && <ResultCard blob={result} filename={`${baseName(file.name)}-signed.pdf`} title="Signed PDF ready" onReset={reset}>
        <div className="text-sm text-muted">Do not edit this file after signing, or the signature will no longer be valid. You can add more signatures later: each one is appended without breaking the earlier ones.</div>
      </ResultCard>}
      <ToolGrid
        main={<div className="rounded-2xl border border-border bg-surface p-4">
          <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
            <Switch checked={visible} onChange={(v) => { setVisible(v); setResult(null) }} label="Show a visible signature box" />
            {visible && numPages > 1 && <PageStepper page={page} total={numPages} onChange={setPage} />}
          </div>
          {visible ? <div className="checker flex min-h-80 items-center justify-center rounded-xl p-4">
            {img && box ? <div className="w-full max-w-[640px]"><RectEditor src={img.src} pageW={img.w} pageH={img.h} selected="sig" onSelect={() => {}} rects={[{ id: 'sig', ...box, label: id ? `Signed by ${id.subject.match(/CN=([^,]+)/)?.[1] ?? ''}` : 'Signature' }]} onChange={(_, r) => { setBox(r); setResult(null) }} /></div> : <Spinner label="Rendering…" />}
          </div> : <div className="rounded-xl bg-surface-2/60 p-6 text-center text-sm text-muted">The signature is stored invisibly. PDF readers still list it in their signature panel.</div>}
          {visible && <div className="mt-2 text-xs text-muted">Drag the box to place the signature, use its corner to resize.</div>}
        </div>}
        side={<>
          {!cert ? <>
            <Dropzone compact accept=".p12,.pfx,application/x-pkcs12" onFiles={(f) => setCert(f[0])} label="Add your certificate (.p12 / .pfx)" />
            <Button variant="outline" className="w-full" icon={<KeyRound className="size-4" />} onClick={() => setMaker(!maker)}>{maker ? 'Hide' : 'No certificate? Create one'}</Button>
            {maker && <Card className="space-y-2 p-3">
              <Field label="Your name"><Input value={mk.name} onChange={(e) => setMk({ ...mk, name: e.target.value })} /></Field>
              <Field label="Email (optional)"><Input value={mk.email} onChange={(e) => setMk({ ...mk, email: e.target.value })} /></Field>
              <Field label="Organization (optional)"><Input value={mk.org} onChange={(e) => setMk({ ...mk, org: e.target.value })} /></Field>
              <Field label="New password for the file"><Input type="password" value={mk.password} onChange={(e) => setMk({ ...mk, password: e.target.value })} /></Field>
              <ErrorNote error={make.error} />
              <Button size="sm" className="w-full" icon={<Download className="size-3.5" />} loading={make.busy} onClick={makeCert}>Create and download</Button>
              <div className="text-xs text-muted">A self-signed certificate proves the file was not changed after you signed it. Readers will say the signer is unknown until they trust your certificate. For legally recognised signatures use one from a trusted provider.</div>
            </Card>}
          </> : <>
            <FileChip file={cert} onRemove={() => { setCert(null); setId(null); setPassword('') }} />
            {!id ? <>
              <Field label="Certificate password"><Input type="password" value={password} autoFocus onChange={(e) => setPassword(e.target.value)} onKeyDown={(e) => e.key === 'Enter' && open()} /></Field>
              <ErrorNote error={unlock.error} />
              <Button className="w-full" variant="outline" icon={<FileKey2 className="size-4" />} loading={unlock.busy} onClick={open}>Open certificate</Button>
            </> : <div className="rounded-xl border border-success/30 bg-success/5 p-3 text-xs">
              <div className="flex items-center gap-1.5 text-sm font-semibold text-success"><ShieldCheck className="size-4" />Certificate ready</div>
              <div className="mt-1 break-words"><span className="text-muted">Signer:</span> {id.subject}</div>
              <div className="break-words"><span className="text-muted">Issued by:</span> {id.issuer === id.subject ? 'self-signed' : id.issuer}</div>
              <div><span className="text-muted">Valid until:</span> {id.notAfter.toLocaleDateString()}</div>
            </div>}
          </>}
          <Field label="Reason (optional)"><Input value={reason} placeholder="I approve this document" onChange={(e) => { setReason(e.target.value); setResult(null) }} /></Field>
          <div className="grid grid-cols-2 gap-2">
            <Field label="Location"><Input value={location} onChange={(e) => { setLocation(e.target.value); setResult(null) }} /></Field>
            <Field label="Contact"><Input value={contact} onChange={(e) => { setContact(e.target.value); setResult(null) }} /></Field>
          </div>
          <Note>Signs with SHA-256 as a standard PDF digital signature (PKCS#7 detached). Your certificate and password stay in this browser tab.</Note>
          {job.busy && <Progress value={job.progress} label="Signing…" />}
          <ErrorNote error={job.error} />
          <Button className="w-full" size="lg" icon={<FileKey2 className="size-5" />} loading={job.busy} disabled={!id || !numPages} onClick={sign}>Sign PDF</Button>
        </>}
      />
    </div>
  )
}
